create table if not exists public.profiles (
  slug text primary key,
  full_name text not null,
  headline text not null,
  highlight text,
  bio text not null,
  photo_url text,
  published boolean not null default true
);

create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  category text not null unique,
  icon text,
  items text[] not null default '{}',
  sort_order integer not null default 0,
  published boolean not null default true
);

create table if not exists public.certifications (
  id bigint generated by default as identity primary key,
  title text not null,
  issuer text not null,
  issued_on date not null,
  published boolean not null default true,
  unique (title, issuer, issued_on)
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  category text not null,
  description text not null,
  tags text[] not null default '{}',
  link_url text,
  link_label text,
  sort_order integer not null default 0,
  published boolean not null default true,
  constraint project_link_https check (link_url is null or link_url like 'https://%')
);

alter table public.profiles enable row level security;
alter table public.skills enable row level security;
alter table public.certifications enable row level security;
alter table public.projects enable row level security;

drop policy if exists "Public profiles are readable" on public.profiles;
create policy "Public profiles are readable" on public.profiles for select to anon, authenticated using (published = true);
drop policy if exists "Public skills are readable" on public.skills;
create policy "Public skills are readable" on public.skills for select to anon, authenticated using (published = true);
drop policy if exists "Public certifications are readable" on public.certifications;
create policy "Public certifications are readable" on public.certifications for select to anon, authenticated using (published = true);
drop policy if exists "Public projects are readable" on public.projects;
create policy "Public projects are readable" on public.projects for select to anon, authenticated using (published = true);

grant usage on schema public to anon, authenticated;
grant select on public.profiles, public.skills, public.certifications, public.projects to anon, authenticated;
revoke insert, update, delete on public.profiles, public.skills, public.certifications, public.projects from anon, authenticated;

